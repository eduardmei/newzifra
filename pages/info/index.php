  $size = $orientation === 'vertical' ? '1240×1754' : '1136×768';
  $label = $orientation === 'vertical' ? 'Вертикальное фото' : 'Горизонтальное фото';
  ?>
  <article class="achievement-card <?php echo $class; ?> <?php echo $ratio; ?>"
           data-year="<?php echo $year; ?>"
           data-title="<?php echo $title; ?>"
           data-description="">
